    @Override
    public void onCreate(SQLiteDatabase db) {
        db.execSQL("CREATE TABLE chapters (" +
                "chapter_id TEXT PRIMARY KEY, " +
                "chapter_order INTEGER, " +
                "title TEXT, " +
                "start_scene_id TEXT, " +
                "is_unlocked INTEGER)");

        db.execSQL("CREATE TABLE scenes (" +
                "scene_id TEXT PRIMARY KEY, " +
                "chapter_id TEXT, " +
                "story_text TEXT, " +
                "is_game_over INTEGER, " +
                "next_page_id TEXT)");

        db.execSQL("CREATE TABLE choices (" +
                "id INTEGER PRIMARY KEY AUTOINCREMENT, " +
                "scene_id TEXT, " +
                "choice_text TEXT, " +
                "next_scene_id TEXT)");

        populateFullStory(db);
    }

    @Override
    public void onUpgrade(SQLiteDatabase db, int oldVersion, int newVersion) {
        db.execSQL("DROP TABLE IF EXISTS choices");
        db.execSQL("DROP TABLE IF EXISTS scenes");
        db.execSQL("DROP TABLE IF EXISTS chapters");
        onCreate(db);
    }

    private void addChapter(SQLiteDatabase db, String id, int order, String title, String startSceneId, boolean unlocked) {
        ContentValues cv = new ContentValues();
        cv.put("chapter_id", id);
        cv.put("chapter_order", order);
        cv.put("title", title);
        cv.put("start_scene_id", startSceneId);
        cv.put("is_unlocked", unlocked ? 1 : 0);
        db.insert("chapters", null, cv);
    }

    private void addPage(SQLiteDatabase db, String sceneId, String chapterId, String text, String nextPageId) {
        ContentValues cv = new ContentValues();
        cv.put("scene_id", sceneId);
        cv.put("chapter_id", chapterId);
        cv.put("story_text", text);
        cv.put("is_game_over", 0);
        cv.put("next_page_id", nextPageId);
        db.insert("scenes", null, cv);
    }

    private void addBranchOrGameOver(SQLiteDatabase db, String sceneId, String chapterId, String text, boolean isGameOver) {
        ContentValues cv = new ContentValues();
        cv.put("scene_id", sceneId);
        cv.put("chapter_id", chapterId);
        cv.put("story_text", text);
        cv.put("is_game_over", isGameOver ? 1 : 0);
        cv.put("next_page_id", (String) null);
        db.insert("scenes", null, cv);
    }

    private void addChoice(SQLiteDatabase db, String sceneId, String choiceText, String nextSceneId) {
        ContentValues cv = new ContentValues();
        cv.put("scene_id", sceneId);
        cv.put("choice_text", choiceText);
        cv.put("next_scene_id", nextSceneId);
        db.insert("choices", null, cv);
    }

    public void unlockChapter(String chapterId) {
        if (chapterId == null) return;
        SQLiteDatabase db = this.getWritableDatabase();
        ContentValues cv = new ContentValues();
        cv.put("is_unlocked", 1);
        db.update("chapters", cv, "chapter_id = ?", new String[]{chapterId});
    }

    public void resetUnlockedChapters() {
        SQLiteDatabase db = this.getWritableDatabase();
        ContentValues lockAll = new ContentValues();
        lockAll.put("is_unlocked", 0);
        db.update("chapters", lockAll, null, null);

        ContentValues unlockFirst = new ContentValues();
        unlockFirst.put("is_unlocked", 1);
        db.update("chapters", unlockFirst, "chapter_id = ?", new String[]{"ch1"});
    }

    public List<ChapterItem> getAllChapters() {
        List<ChapterItem> list = new ArrayList<>();
        SQLiteDatabase db = this.getReadableDatabase();
        Cursor c = db.rawQuery("SELECT chapter_id, title, start_scene_id, is_unlocked FROM chapters ORDER BY chapter_order ASC", null);
        if (c.moveToFirst()) {
            do {
                list.add(new ChapterItem(
                        c.getString(0),
                        c.getString(1),
                        c.getString(2),
                        c.getInt(3) == 1
                ));
            } while (c.moveToNext());
        }
        c.close();
        return list;
    }

    public SceneData getScene(String sceneId) {
        SQLiteDatabase db = this.getReadableDatabase();
        Cursor c = db.rawQuery("SELECT scene_id, chapter_id, story_text, is_game_over, next_page_id FROM scenes WHERE scene_id = ?", new String[]{sceneId});
        if (!c.moveToFirst()) {
            c.close();
            return null;
        }

        SceneData scene = new SceneData(
                c.getString(0),
                c.getString(1),
                c.getString(2),
                c.getInt(3) == 1,
                c.getString(4)
        );
        c.close();

        Cursor cc = db.rawQuery("SELECT choice_text, next_scene_id FROM choices WHERE scene_id = ?", new String[]{sceneId});
        if (cc.moveToFirst()) {
            do {
                scene.choices.add(new ChoiceItem(cc.getString(0), cc.getString(1)));
            } while (cc.moveToNext());
        }
        cc.close();
        return scene;
    }

